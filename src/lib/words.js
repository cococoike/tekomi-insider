export function pickFrom(pool, used = [], keyOf = (x) => JSON.stringify(x)) {
  const available = pool.filter((x) => !used.includes(keyOf(x)));
  const source = available.length > 0 ? available : pool;
  return source[Math.floor(Math.random() * source.length)];
}

// ワードウルフのペアを1組引く（アダルトONなら成人ペアのみ）。返り値 [多数派, 少数派]（ランダム入替済み）
export function pickWolfPair(used = [], adult = false) {
  const pool = adult ? WOLF_PAIRS_ADULT : WOLF_PAIRS;
  const pair = pickFrom(pool, used, (p) => p.join("|"));
  return Math.random() < 0.5 ? [pair[0], pair[1]] : [pair[1], pair[0]];
}

// ワードジャマーの質問カードを1枚引く（アダルトONなら成人質問も混ざる）
export function pickJammerQuestion(used = [], adult = false) {
  const pool = adult ? [...JAMMER_QUESTIONS, ...JAMMER_QUESTIONS_ADULT] : JAMMER_QUESTIONS;
  return pickFrom(pool, used, (x) => x.q);
}

// 魔術カードを人数分、重複なしで配る（人数が多ければ繰り返し可）
export function dealMagicCards(n) {
  const shuffled = shuffle(MAGIC_CARDS);
  const out = [];
  for (let i = 0; i < n; i++) out.push(shuffled[i % shuffled.length]);
  return out;
}

// お題がどのカテゴリの語か（「カテゴリ公開」のヒント用）。アダルトは "アダルト"、不明なら null
export function categoryOf(word) {
  for (const [cat, list] of Object.entries(WORD_LIST)) if (list.includes(word)) return cat;
  return ADULT_LIST.includes(word) ? "アダルト" : null;
}
