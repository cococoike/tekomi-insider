export function pickWord(category, usedWords = [], adult = false) {
  let pool;
  if (adult) {
    pool = ADULT_LIST;
  } else if (category === "おまかせ") {
    pool = Object.values(WORD_LIST).flat();
  } else {
    pool = WORD_LIST[category] || Object.values(WORD_LIST).flat();
  }
  const available = pool.filter((w) => !usedWords.includes(w));
  const source = available.length > 0 ? available : pool;
  return source[Math.floor(Math.random() * source.length)];
}

// 使用済みを避けつつランダムに1つ取り出す（配列要素は文字列でもオブジェクトでもOK。key で重複判定）
export function pickFrom(pool, used = [], keyOf = (x) => JSON.stringify(x)) {
  const available = pool.filter((x) => !used.includes(keyOf(x)));
  const source = available.length > 0 ? available : pool;
  return source[Math.floor(Math.random() * source.length)];
}

